/** Description-only enrichment. Existing non-empty values and operator notes are retained. */
export interface CalendarCourseInfo {
  title?: string | null;
  courseCode?: string | null;
  courseRunId?: string | null;
  courseCodeAliases?: string[];
}

type Field = 'title' | 'courseCode' | 'courseRunId';
const labels: Record<Field, string> = { title: 'Course Title', courseCode: 'Course Code', courseRunId: 'Course Run ID' };
const separators = /(\r\n|\r|\n|<br\b[^>]*>|<\/?(?:p|div|li)\b[^>]*>)/gi;
const footer = /\*Auto-generated by LMS(?: \(Company Application\))?(?:; Updated: [^*\r\n<>]*)?\*/gi;
const placeholder = /^(?:n\/?a|none|null|undefined|unknown|tbd|pending|not available|[-–—])?$/i;
const clean = (value: string | null | undefined) => (value || '').replace(/[\r\n]+/g, ' ').trim();
const escape = (value: string) => value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
export const descriptionText = (value: string) => value.replace(/<[^>]*>/g, '').replace(/&nbsp;|&#160;/gi, ' ')
  .replace(/&amp;/gi, '&').replace(/&lt;/gi, '<').replace(/&gt;/gi, '>').trim();

function fieldOf(fragment: string): { field: Field; value: string } | null {
  const match = descriptionText(fragment).match(/^Course\s+(Title|Code|Run\s*ID)\s*:\s*(.*?)\s*$/i);
  if (!match) return null;
  return { field: /^title$/i.test(match[1]) ? 'title' : /^code$/i.test(match[1]) ? 'courseCode' : 'courseRunId', value: match[2] };
}

export function readCalendarCourseInfo(description: string): Record<Field, string[]> {
  const out: Record<Field, string[]> = { title: [], courseCode: [], courseRunId: [] };
  for (const part of description.split(separators)) {
    const field = fieldOf(part);
    if (field && !placeholder.test(field.value)) out[field.field].push(field.value);
  }
  return out;
}

export function calendarUpdatedFooter(now: Date): string {
  const parts = new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Singapore', day: '2-digit', month: 'short',
    year: 'numeric', hour: 'numeric', minute: '2-digit', hour12: true }).formatToParts(now);
  const part = (type: Intl.DateTimeFormatPartTypes) => parts.find(p => p.type === type)!.value;
  return `*Auto-generated by LMS; Updated: ${part('day')} ${part('month')} ${part('year')}, ${part('hour')}:${part('minute')} ${part('dayPeriod').toUpperCase()} SGT*`;
}

export interface CourseInfoDescriptionResult {
  status: 'updated' | 'unchanged' | 'conflict';
  description: string;
  fields: Field[];
  reason?: string;
}

export function enrichCalendarCourseDescription(previous: string | null | undefined, info: CalendarCourseInfo,
  now = new Date()): CourseInfoDescriptionResult {
  const original = previous || '';
  const unchanged = { status: 'unchanged' as const, description: original, fields: [] };
  // The operational writer owns its structured blocks; never edit them through a legacy path.
  if (original.includes('<!-- TMS CLASS')) return { ...unchanged, status: 'conflict', reason: 'operational_description_owned' };
  const values: Record<Field, string> = { title: clean(info.title), courseCode: clean(info.courseCode), courseRunId: clean(info.courseRunId) };
  const existing = readCalendarCourseInfo(original);
  const codes = new Set([values.courseCode, ...(info.courseCodeAliases || [])].map(c => c.trim().toUpperCase()).filter(Boolean));
  for (const key of ['courseRunId', 'courseCode'] as const) {
    if (existing[key].some(value => key === 'courseRunId'
      ? !!values[key] && value !== values[key] : codes.size > 0 && !codes.has(value.toUpperCase()))) {
      return { ...unchanged, status: 'conflict', reason: `conflicting_${key}` };
    }
  }
  const html = /<\/?[a-z][^>]*>/i.test(original);
  const parts = original.split(separators);
  const present = new Set<Field>();
  const changed = new Set<Field>();
  for (let i = 0; i < parts.length; i++) {
    const parsed = fieldOf(parts[i]);
    if (!parsed) continue;
    present.add(parsed.field);
    const value = values[parsed.field];
    if (!value || placeholder.test(value) || !placeholder.test(parsed.value)) continue;
    // Preserve markup, including bold labels, and replace only placeholder text after the colon.
    let afterColon = false, inserted = false;
    parts[i] = parts[i].split(/(<[^>]*>)/g).map(piece => {
      if (/^</.test(piece)) return piece;
      const colon = piece.indexOf(':');
      if (!afterColon && colon >= 0) {
        afterColon = true;
        const tail = piece.slice(colon + 1);
        if (tail.trim()) { inserted = true; return piece.slice(0, colon + 1) + ' ' + (html ? escape(value) : value); }
        return piece;
      }
      if (afterColon && piece.trim()) { inserted = true; return (html ? escape(value) : value); }
      return piece;
    }).join('');
    if (!inserted) parts[i] = parts[i].trimEnd() + ' ' + (html ? escape(value) : value);
    changed.add(parsed.field);
  }
  const additions: string[] = [];
  for (const key of Object.keys(labels) as Field[]) {
    if (!present.has(key) && values[key] && !placeholder.test(values[key])) {
      additions.push(`${labels[key]}: ${html ? escape(values[key]) : values[key]}`);
      changed.add(key);
    }
  }
  if (!changed.size) return unchanged; // Merely checking an event must never advance its timestamp.
  const newline = html ? '<br>' : original.includes('\r\n') ? '\r\n' : '\n';
  const retained = parts.join('').replace(footer, '').trimEnd();
  const description = [retained, additions.join(newline), calendarUpdatedFooter(now)].filter(Boolean).join(newline + newline);
  return { status: 'updated', description, fields: [...changed] };
}
