import { createHash } from 'node:crypto';
import type { Pool } from 'pg';
import { AutomationError } from './model';
import { parseAgentConfiguration, type ConfiguredAgent } from './agentAccess';

export const AGENT_SCHEMA=`CREATE TABLE IF NOT EXISTS google_automation_agent_grant (
 connection_id TEXT NOT NULL,id TEXT NOT NULL,account_email TEXT NOT NULL,
 token_sha256 TEXT NOT NULL UNIQUE,scopes TEXT[] NOT NULL,script_ids TEXT[] NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,created_by TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_at TIMESTAMPTZ,revoked_by TEXT,PRIMARY KEY(connection_id,id));`;

export async function storedAgentForToken(pool:Pool,token:string):Promise<ConfiguredAgent|null>{
  // Authentication never creates schema or modifies a grant.
  if(!(await pool.query("SELECT to_regclass('public.google_automation_agent_grant') AS name")).rows[0]?.name)return null;
  const digest=createHash('sha256').update(token).digest('hex');
  const row=(await pool.query(`SELECT id,account_email AS "accountEmail",token_sha256 AS "tokenSha256",scopes,script_ids AS "scriptIds",expires_at AS "expiresAt"
    FROM google_automation_agent_grant WHERE token_sha256=$1 AND revoked_at IS NULL AND expires_at>now()`,[digest])).rows[0];
  return row?{...row,expiresAt:new Date(row.expiresAt).toISOString()}:null;
}

export class AutomationAgentStore {
  constructor(private pool:Pool,private connection:string,private accountEmail:string){}
  async init(){
    const client=await this.pool.connect();
    try{await client.query("SELECT pg_advisory_lock(hashtext('google-automation-agent-schema-v1'))");await client.query(AGENT_SCHEMA);}
    finally{await client.query("SELECT pg_advisory_unlock(hashtext('google-automation-agent-schema-v1'))").catch(()=>{});client.release();}
  }
  async list(){
    return (await this.pool.query(`SELECT id,account_email AS "accountEmail",scopes,script_ids AS "scriptIds",expires_at AS "expiresAt",created_at AS "createdAt",created_by AS "createdBy",revoked_at AS "revokedAt",revoked_by AS "revokedBy"
      FROM google_automation_agent_grant WHERE connection_id=$1 ORDER BY created_at DESC,id`,[this.connection])).rows;
  }
  async install(input:unknown,actor:string,acknowledged:unknown,canPublish:boolean){
    if(acknowledged!==true)throw new AutomationError(400,'Acknowledge the agent permissions and expiry before authorizing access.');
    let grant:ConfiguredAgent;
    try{grant=parseAgentConfiguration(JSON.stringify([input]))[0];}catch{throw new AutomationError(400,'Choose a valid agent grant generated by the source tool.');}
    if(grant.accountEmail!==this.accountEmail)throw new AutomationError(403,'The grant belongs to another Google account.');
    if(Date.parse(grant.expiresAt)<=Date.now())throw new AutomationError(400,'The agent grant has expired.');
    if(grant.scopes.includes('publish')&&!canPublish)throw new AutomationError(403,'Publishing is disabled for this account or server.');
    if(!grant.scriptIds.includes('*')){
      const projects=(await this.pool.query('SELECT script_id FROM google_automation_project WHERE connection_id=$1 AND script_id=ANY($2::text[])',[this.connection,grant.scriptIds])).rows;
      if(new Set(projects.map(p=>p.script_id)).size!==new Set(grant.scriptIds).size)throw new AutomationError(400,'Register all listed Google projects before authorizing this grant.');
    }
    const saved=await this.pool.query(`INSERT INTO google_automation_agent_grant(connection_id,id,account_email,token_sha256,scopes,script_ids,expires_at,created_by)
      VALUES($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT DO NOTHING RETURNING id`,[this.connection,grant.id,grant.accountEmail,grant.tokenSha256,grant.scopes,grant.scriptIds,grant.expiresAt,actor]);
    if(!saved.rowCount)throw new AutomationError(409,'That agent ID or credential is already registered. Use a new ID and credential.');
    return this.list();
  }
  async revoke(id:unknown,actor:string){
    if(typeof id!=='string'||!/^[-\w]{1,64}$/.test(id))throw new AutomationError(400,'Invalid agent ID.');
    const changed=await this.pool.query(`UPDATE google_automation_agent_grant SET revoked_at=COALESCE(revoked_at,now()),revoked_by=COALESCE(revoked_by,$3)
      WHERE connection_id=$1 AND id=$2 RETURNING id`,[this.connection,id,actor]);
    if(!changed.rowCount)throw new AutomationError(404,'Agent grant not found.');
    return this.list();
  }
}
