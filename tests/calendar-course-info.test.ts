test('local HTTP transport sends only a conditional description patch and preserves attendees/time', async () => {
  let remote = event(), requests = 0;
  const server = createServer((req, res) => {
    if (req.method === 'PATCH') {
      assert.equal(req.headers['if-match'], 'v1');
      let body = ''; req.on('data', chunk => { body += chunk; });
      req.on('end', () => { const patch = JSON.parse(body); assert.deepEqual(Object.keys(patch), ['description']);
        remote = { ...remote, ...patch, etag: 'v2' }; requests++; res.end('{}'); });
    } else { res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify(remote)); }
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  try {
    const result = await refreshExistingCalendarCourseInfo({ runs: async () => [run()], events: async () => [event()],
      get: async () => (await fetch(origin)).json(), lock: async (_id, fn) => fn(),
      patch: async (_id, description, etag) => { const response = await fetch(origin, { method: 'PATCH',
        headers: { 'Content-Type': 'application/json', 'If-Match': etag }, body: JSON.stringify({ description }) }); assert.equal(response.status, 200); },
    }, { now });
    assert.equal(result.updated, 1); assert.equal(requests, 1);
    assert.deepEqual(remote.attendees, event().attendees); assert.deepEqual(remote.start, event().start);
  } finally { await new Promise<void>(resolve => server.close(() => resolve())); }
});

