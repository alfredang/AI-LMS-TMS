type Event = calendar_v3.Schema$Event;
function run(overrides: Partial<CourseInfoRun> = {}): CourseInfoRun {
  return { ...info, id: 'run-one', startDate: '2026-11-23', endDate: '2026-11-24', active: true,
    sessionDates: ['2026-11-23', '2026-11-24'], mappings: [{ eventId: 'event-one', date: '2026-11-24' }], ...overrides };
}
function event(overrides: Event = {}): Event {
  return { id: 'event-one', etag: 'v1', status: 'confirmed', description: 'Operator note',
    start: { dateTime: '2026-11-24T09:30:00+08:00' }, attendees: [{ email: 'manual@example.test', responseStatus: 'accepted' }],
    ...overrides };
}
function fixture(runs: CourseInfoRun[], events: Event[]) {
  const remote = new Map(events.map(e => [e.id!, structuredClone(e)]));
  const patches: { eventId: string; description: string; etag: string }[] = [];
  const deps: CourseInfoRefreshDependencies = { runs: async () => structuredClone(runs), events: async () => structuredClone(events),
    get: async id => structuredClone(remote.get(id)!), lock: async (_id, fn) => fn(),
    patch: async (eventId, description, etag) => { patches.push({ eventId, description, etag }); remote.set(eventId, { ...remote.get(eventId), description, etag: 'v2' }); } };
  return { deps, remote, patches };
}

