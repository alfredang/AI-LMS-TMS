// Exercises the real local review login and APIs. No fixture responses, no
// operational database and no Google source changes.
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const settings=JSON.parse(await fs.readFile('config/google-automations-review.private.json','utf8'));
const {review}=settings;
assert.equal(settings.allowPublish,false);
assert.equal(review.database.database,'google_automation_review');
const origin='http://localhost:3004';
const login=await fetch(origin+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:review.email,password:review.password,loginType:'password'}),signal:AbortSignal.timeout(120000)});
const signedIn=await login.json();
assert.equal(login.status,200,signedIn.error || 'Local password login failed');
assert.equal(signedIn.success,true);
const headers={Authorization:`Bearer ${signedIn.data.token}`};
const get=async query=>{
  const response=await fetch(origin+'/api/admin/google-automations'+query,{headers,signal:AbortSignal.timeout(120000)});
  const body=await response.json();assert.equal(response.status,200,body.error);return body;
};
const registry=await get('');
assert.equal(registry.enabled,true);assert.equal(registry.capabilities.canPublish,false);
assert.ok(registry.projects.length>=17);
const account=await get('?view=connection');assert.equal(account.accountEmail,settings.accountEmail);
const project=registry.projects.find(p=>p.name==='Add Orders to Calendar');assert.ok(project);
const source=await get(`?view=source&scriptId=${project.scriptId}`);
assert.ok(source.files.some(f=>f.source.includes('function detectNewOrders')));
const blocked=await fetch(origin+'/api/admin/google-automations',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({action:'publish'}),signal:AbortSignal.timeout(30000)});
assert.equal(blocked.status,403);
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(review.url,{waitUntil:'domcontentloaded',timeout:120000});
  const passwordMode=page.getByRole('button',{name:/^(Use Password|Login with password instead)$/});
  await page.locator('#password-login').or(passwordMode).first().waitFor({timeout:60000});
  if(await passwordMode.isVisible())await passwordMode.click();
  await page.locator('#email-pw').fill(review.email);
  await page.locator('#password-login').fill(review.password);
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await page.waitForFunction(()=>!!localStorage.getItem('auth_token'),{timeout:120000});
  await page.goto(review.url,{waitUntil:'domcontentloaded',timeout:120000});
  await page.getByRole('heading',{name:'Google Automations',exact:true}).waitFor({timeout:120000});
  await page.getByRole('button',{name:/Add Orders to Calendar/}).waitFor({timeout:120000});
  await page.getByRole('button',{name:/Add Orders to Calendar/}).click();
  await fs.mkdir('outputs/google-automations',{recursive:true});
  await page.getByRole('button',{name:'Source',exact:true}).click();
  await page.getByRole('textbox',{name:'Source code for Code',exact:true}).waitFor({timeout:120000});
  assert.match(await page.getByRole('textbox',{name:'Source code for Code',exact:true}).inputValue(),/detectNewOrders/);
  const editor=page.getByRole('textbox',{name:'Source code for Code',exact:true});
  const metrics=await editor.evaluate(el=>({fontSize:getComputedStyle(el).fontSize,lineHeight:getComputedStyle(el).lineHeight,rows:el.rows,height:el.clientHeight}));
  assert.equal(metrics.fontSize,'16px');assert.equal(metrics.lineHeight,'24px');assert.equal(metrics.rows,30);assert.ok(metrics.height>=750);
  assert.match(await page.getByTestId('numbered-source-editor').locator('pre').innerText(),/^1\n2\n3\n/);
  await editor.evaluate(el=>{el.scrollTop=240;el.dispatchEvent(new Event('scroll',{bubbles:true}));});
  assert.equal(await page.getByTestId('numbered-source-editor').locator('div[aria-hidden=true]').evaluate(el=>el.scrollTop),240);
  await editor.fill((await editor.inputValue())+'\n// Local UI review: highlighted source changes.\n');
  await page.locator('#automation-reason').fill('Local UI review of highlighted source changes');
  await page.getByRole('button',{name:'Save draft and review',exact:true}).click();
  await page.getByLabel('Proposed source',{exact:true}).waitFor({timeout:120000});
  assert.ok(await page.getByLabel('Proposed source',{exact:true}).locator('[data-change=added]').count()>0);
  await page.screenshot({path:'outputs/google-automations/localhost-diff-review-2026-11-05.png',fullPage:true});
  await page.getByRole('button',{name:'Triggers',exact:true}).click();
  await page.getByRole('heading',{name:'detectNewOrders',exact:true}).waitFor({timeout:60000});
  assert.ok(await page.getByRole('button',{name:'Edit trigger',exact:true}).isEnabled());
  await page.getByRole('button',{name:'Edit trigger',exact:true}).click();
  await page.getByLabel('Trigger interval',{exact:true}).selectOption('5');
  await page.getByLabel('Trigger change reason',{exact:true}).fill('Local UI verification: change interval to five minutes');
  await page.getByRole('button',{name:'Save trigger draft',exact:true}).click();
  const localAck=page.getByRole('checkbox',{name:'I reviewed this change. Apply it only to the local review; keep Google unchanged.',exact:true}).last();
  await localAck.check();await page.getByRole('button',{name:'Apply to local review',exact:true}).last().click();
  await page.getByRole('status').filter({hasText:'Applied to local review.'}).waitFor({timeout:60000});
  let triggerState=await get(`?view=triggers&scriptId=${project.scriptId}`);
  assert.equal(triggerState.rows[0].settings.schedule.every,5);assert.equal(triggerState.rows[0].baseline.schedule.every,30);
  await page.getByRole('button',{name:'Edit trigger',exact:true}).click();
  await page.getByLabel('Trigger interval',{exact:true}).selectOption('30');
  await page.getByLabel('Trigger change reason',{exact:true}).fill('Local UI verification complete: restore review baseline');
  await page.getByRole('button',{name:'Save trigger draft',exact:true}).click();
  await page.getByRole('checkbox',{name:'I reviewed this change. Apply it only to the local review; keep Google unchanged.',exact:true}).last().check();
  await page.getByRole('button',{name:'Apply to local review',exact:true}).last().click();
  await page.getByRole('status').filter({hasText:'Applied to local review.'}).waitFor({timeout:60000});
  triggerState=await get(`?view=triggers&scriptId=${project.scriptId}`);assert.equal(triggerState.rows[0].settings.schedule.every,30);
  await fs.mkdir('outputs/google-automations',{recursive:true});
  await page.screenshot({path:'outputs/google-automations/localhost-review-2026-11-05.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await page.screenshot({path:'outputs/google-automations/localhost-triggers-review-2026-11-05.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
  await page.screenshot({path:'outputs/google-automations/localhost-triggers-mobile-2026-11-05.png',fullPage:true});
  console.log(`Local review verified: normal login, ${registry.projects.length} projects, Google reads, 30-line numbered 16px editor, highlighted source draft, persisted trigger review edits, mobile layout and source publication blocked. Google was not changed.`);
} catch(error) {
  await page.screenshot({path:'outputs/google-automations/localhost-review-failure.png',fullPage:true}).catch(()=>{});
  throw error;
} finally {await browser.close();}
